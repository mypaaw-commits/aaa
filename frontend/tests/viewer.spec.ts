import { expect, test } from '@playwright/test';
import { loadExample } from './fixtures';

test('Selection leaves the camera unchanged; Blender orbit, pan, zoom and framing work', async ({ page }) => {
  await page.goto('/');
  await loadExample(page);
  const a = page.locator('.object-row').filter({ hasText: 'A.stl' });
  const b = page.locator('.object-row').filter({ hasText: 'B.stl' });
  const canvas = page.locator('canvas');
  await a.locator('.object-select').click();
  await page.waitForTimeout(300);
  let before = await canvas.screenshot();
  await b.locator('.object-select').click();
  await a.locator('.object-select').click();
  expect(Buffer.compare(before, await canvas.screenshot())).toBe(0);
  const bounds = (await canvas.boundingBox())!;
  const x = bounds.x + bounds.width / 2, y = bounds.y + bounds.height / 2;
  await page.mouse.move(x, y);
  await page.mouse.down({ button: 'middle' });
  await page.mouse.move(x + 80, y + 30, { steps: 8 });
  await page.mouse.up({ button: 'middle' });
  await page.waitForTimeout(350);
  let after = await canvas.screenshot();
  expect(Buffer.compare(before, after)).not.toBe(0);
  before = after;
  await page.keyboard.down('Shift');
  await page.mouse.down({ button: 'middle' });
  await page.mouse.move(x + 130, y + 60, { steps: 8 });
  await page.mouse.up({ button: 'middle' });
  await page.keyboard.up('Shift');
  await page.waitForTimeout(350);
  after = await canvas.screenshot();
  expect(Buffer.compare(before, after)).not.toBe(0);
  before = after;
  await page.mouse.wheel(0, -200);
  await page.waitForTimeout(300);
  expect(Buffer.compare(before, await canvas.screenshot())).not.toBe(0);
  await b.locator('.object-select').click();
  await page.getByRole('button', { name: 'Isolate selection', exact: true }).click();
  await expect(page.locator('.scene-label')).toContainText('1 / 3 visible');
  await page.getByRole('button', { name: 'Clear selection', exact: true }).click();
  await canvas.click({ position: { x: bounds.width / 2, y: bounds.height / 2 } });
  await expect(b).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('button', { name: 'Back to full model', exact: true }).click();
  await expect(page.locator('.scene-label')).toContainText('3 / 3 visible');
  await page.waitForTimeout(300);
  before = await canvas.screenshot();
  await page.getByRole('button', { name: 'Floor', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Floor', exact: true })).toHaveAttribute('aria-pressed', 'false');
  expect(Buffer.compare(before, await canvas.screenshot())).not.toBe(0);
});
