import { test, expect } from '@playwright/test';
import { loadExample, stlBox } from './fixtures';

test('Grouped connections, independent part reviews, notes and stale checks', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'No model loaded' })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('empty.png') });
  await expect(page.getByRole('button', { name: 'Choose STL files', exact: true })).toBeEnabled();
  const [chooser] = await Promise.all([page.waitForEvent('filechooser'), page.getByRole('button', { name: 'Choose STL files', exact: true }).click()]);
  await chooser.setFiles([stlBox('A.stl', -12, 8, -4), stlBox('B.stl', -4, 8, -4), stlBox('C.stl', 3.5, 8, -4)]);
  await expect(page.locator('.object-row')).toHaveCount(3);
  await expect(page.locator('.geometry-loading')).toHaveCount(0);
  const a = page.locator('.object-row').filter({ hasText: 'A.stl' });
  await a.locator('.object-select').click();
  await page.screenshot({ path: testInfo.outputPath('selection.png') });
  await expect(page.locator('.review-row')).toHaveCount(3);
  await expect(page.locator('.review-row input[type=checkbox]')).toHaveCount(0);
  await page.getByRole('button', { name: 'Find connections', exact: true }).click();
  await expect(page.locator('.analysis-heading')).toHaveText('Connections updated');
  await expect(page.locator('#relations-panel .connection-group-toggle')).toHaveCount(3);
  await expect(page.locator('#relations-panel .result-pair')).toHaveCount(0);
  await page.getByRole('button', { name: 'Connections of A.stl', exact: true }).click();
  await expect(page.locator('#relations-panel .result-pair')).toHaveCount(1);
  await expect(page.locator('#relations-panel .pair-status')).toHaveText('Connected');
  await expect(page.locator('#relations-panel .pair-symbol svg')).toHaveClass(/lucide-link/);
  await expect(page.locator('.object-row[aria-selected=true]')).toHaveCount(1);
  await page.screenshot({ path: testInfo.outputPath('connections.png') });
  await expect(page.locator('.review-row input[type=checkbox]')).toHaveCount(0);
  await page.waitForTimeout(300);
  await page.getByRole('button', { name: 'Select pair: A.stl / B.stl', exact: true }).click();
  await expect(page.locator('.object-row[aria-selected=true]')).toHaveCount(2);
  await expect(a.locator('.part-swatch')).toHaveCSS('background-color', 'rgb(98, 140, 168)');
  await expect(page.locator('.object-row').filter({ hasText: 'B.stl' }).locator('.part-swatch')).toHaveCSS('background-color', 'rgb(178, 149, 98)');
  await expect(page.locator('.scene-label')).toContainText('3 / 3 visible');
  const before = await page.locator('canvas').screenshot();
  await page.getByRole('tab', { name: 'Checks', exact: true }).click();
  await page.getByRole('tab', { name: 'Checks', exact: true }).press('ArrowLeft');
  await expect(page.getByRole('tab', { name: 'Connections', exact: true })).toBeFocused();
  expect(Buffer.compare(before, await page.locator('canvas').screenshot())).toBe(0);
  await page.getByRole('button', { name: 'Zoom to pair: A.stl / B.stl', exact: true }).click();
  await expect(page.locator('.scene-label')).toContainText('3 / 3 visible');
  await page.getByRole('button', { name: 'Isolate pair: A.stl / B.stl', exact: true }).click();
  await expect(page.locator('.scene-label')).toContainText('2 / 3 visible');
  await expect(page.locator('.object-row[aria-selected=true]')).toHaveCount(2);
  await page.screenshot({ path: testInfo.outputPath('selected-pair.png') });
  await page.getByRole('button', { name: 'Back to full model', exact: true }).click();
  await page.getByRole('button', { name: 'Check intersections', exact: true }).click();
  await expect(page.locator('.review-row input[type=checkbox]')).toHaveCount(3);
  await expect(page.locator('.checks-pairs-section .result-pair')).toHaveCount(1);
  await expect(page.locator('.review-count')).toHaveText('0 / 3 reviewed');
  await expect(page.getByLabel('Show intersections', { exact: true })).toBeChecked();
  await expect(page.getByRole('button', { name: 'Transparency', exact: true })).toHaveAttribute('aria-pressed', 'false');
  await page.getByRole('button', { name: 'Transparency', exact: true }).click();
  await page.screenshot({ path: testInfo.outputPath('analysis.png') });
  await page.getByTitle('Hide B.stl', { exact: true }).click();
  await page.getByRole('button', { name: 'Inspect pair: B.stl / C.stl', exact: true }).click();
  await expect(page.locator('.scene-label')).toContainText('2 / 3 visible');
  await expect(page.locator('.object-row[aria-selected=true]')).toHaveCount(2);
  await expect(a).toHaveAttribute('aria-selected', 'false');
  await expect(page.locator('.review-row input:checked')).toHaveCount(0);
  await page.waitForTimeout(200);
  await page.screenshot({ path: testInfo.outputPath('intersection-closeup.png') });
  await page.getByRole('button', { name: 'Back to full model', exact: true }).click();
  const bReview = page.getByRole('checkbox', { name: 'Reviewed: B.stl', exact: true });
  await bReview.check();
  await expect(page.getByRole('checkbox', { name: 'Reviewed: C.stl', exact: true })).not.toBeChecked();
  await expect(page.locator('.review-count')).toHaveText('1 / 3 reviewed');
  await expect(a).toHaveAttribute('aria-selected', 'false');
  await page.getByRole('button', { name: 'Notes: B.stl', exact: true }).click();
  await page.getByRole('textbox', { name: 'Notes: B.stl', exact: true }).fill('Inspect the peg before printing.');
  await page.getByRole('textbox', { name: 'Notes: B.stl', exact: true }).blur();
  await page.screenshot({ path: testInfo.outputPath('notes.png') });
  await page.getByRole('button', { name: 'Check intersections', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Check intersections', exact: true })).toBeEnabled();
  await expect(bReview).toBeChecked();
  await expect(page.getByRole('textbox', { name: 'Notes: B.stl', exact: true })).toHaveValue('Inspect the peg before printing.');
  await page.locator('input[type=file]').setInputFiles([stlBox('D.stl', 40)]);
  await expect(page.locator('.object-row')).toHaveCount(4);
  await expect(page.locator('.review-row input:disabled')).toHaveCount(3);
  await expect(page.locator('.review-row input:checked')).toHaveCount(0);
  await expect(page.locator('.checks-pairs-section .result-pair')).toHaveCount(0);
  await expect(page.getByLabel('Show intersections', { exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Check intersections', exact: true }).click();
  await expect(page.locator('.review-row input[type=checkbox]')).toHaveCount(4);
  await expect(page.locator('.review-row input:disabled')).toHaveCount(0);
  expect(errors).toEqual([]);
});

test('Three overlapping objects show three unique pairs and three compact review rows', async ({ page }, testInfo) => {
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Import STL', exact: true })).toBeEnabled();
  await page.locator('input[type=file]').setInputFiles([stlBox('base without socket.stl', 0, 8), stlBox('base.stl', 1, 8), stlBox('base with socket.stl', 2, 8)]);
  await expect(page.locator('.object-row')).toHaveCount(3);
  await page.getByRole('button', { name: 'Check intersections', exact: true }).click();
  await expect(page.locator('.checks-pairs-section .result-pair')).toHaveCount(3);
  await expect(page.locator('.review-row')).toHaveCount(3);
  await expect(page.locator('.review-row input:checked')).toHaveCount(0);
  await expect(page.locator('.review-status.intersectionCount')).toHaveCount(3);
  const names = await page.locator('.checks-pairs-section .result-pair .pair-files').allTextContents();
  expect(new Set(names).size).toBe(3);
  await page.screenshot({ path: testInfo.outputPath('three-pairs.png') });
});

test('Context menu only deletes; dismissal, keyboard and visibility preserve selection', async ({ page }) => {
  await page.goto('/');
  await loadExample(page);
  const rows = page.locator('.object-row');
  const a = rows.filter({ hasText: 'A.stl' }), b = rows.filter({ hasText: 'B.stl' });
  await a.locator('.object-select').click();
  await b.click({ button: 'right' });
  await expect(page.getByRole('menuitem')).toHaveText(['Delete']);
  await expect(a).toHaveAttribute('aria-selected', 'true');
  await expect(b).toHaveAttribute('aria-selected', 'false');
  await page.keyboard.press('Escape');
  await expect(b.locator('.object-select')).toBeFocused();
  await b.locator('.object-select').press('Shift+F10');
  await expect(page.getByRole('menu')).toBeVisible();
  await page.locator('.panel-heading').click();
  await expect(page.getByRole('menu')).toHaveCount(0);
  await expect(rows).toHaveCount(3);
  await expect(rows.locator('button')).toHaveCount(6);
  await page.getByTitle('Hide A.stl', { exact: true }).click();
  await expect(a).toHaveAttribute('aria-selected', 'true');
  await b.click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Delete', exact: true }).click();
  await expect(rows).toHaveCount(2);
  await expect(page.locator('.review-row')).toHaveCount(2);
  await expect(a).toHaveAttribute('aria-selected', 'true');
});
