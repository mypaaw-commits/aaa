import { test, expect } from '@playwright/test';

test('model ABC: render, analyze, inspect, review and scope', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: /Każda część/ })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('empty.png') });
  await page.getByRole('button', { name: /wypróbuj model/ }).click();
  await expect(page.locator('.object-row')).toHaveCount(3);
  await expect(page.locator('.geometry-loading')).toHaveCount(0);
  await expect(page.locator('canvas')).toBeVisible();
  await expect(page.getByRole('button', { name: /^Intersekcje/ })).toHaveAttribute('aria-pressed', 'false');
  const canvas = page.locator('canvas');
  const bounds = (await canvas.boundingBox())!;
  const cx = bounds.x + bounds.width / 2, cy = bounds.y + bounds.height / 2;
  await page.waitForTimeout(200);
  let before = await canvas.screenshot();
  await page.mouse.move(cx, cy);
  await page.mouse.down({ button: 'middle' });
  await page.mouse.move(cx + 70, cy + 25, { steps: 8 });
  await page.mouse.up({ button: 'middle' });
  await page.waitForTimeout(300);
  let after = await canvas.screenshot();
  expect(Buffer.compare(before, after), 'Middle mouse must rotate the rendered scene').not.toBe(0);
  before = after;
  await page.keyboard.down('Shift');
  await page.mouse.down({ button: 'middle' });
  await page.mouse.move(cx + 100, cy + 60, { steps: 8 });
  await page.mouse.up({ button: 'middle' });
  await page.keyboard.up('Shift');
  await page.waitForTimeout(300);
  after = await canvas.screenshot();
  expect(Buffer.compare(before, after), 'Shift + middle mouse must change the rendered view').not.toBe(0);
  before = after;
  await page.mouse.wheel(0, -200);
  await page.waitForTimeout(300);
  after = await canvas.screenshot();
  expect(Buffer.compare(before, after), 'Scroll wheel must zoom the rendered scene').not.toBe(0);
  await page.getByTitle('Dopasuj kamerę do widocznych części').click();
  await page.getByRole('button', { name: 'Analizuj połączenia' }).click();
  await expect(page.locator('.analysis-heading')).toContainText('Analiza zakończona');
  await expect(page.locator('.statusbar')).toContainText('3 przeanalizowanych par');
  await expect(page.locator('.check-part')).toHaveCount(3);
  // A-B and B-C appear under both elements, but there are only two unique review records.
  await expect(page.locator('.relation-row')).toHaveCount(4);
  await expect(page.locator('.review-progress strong')).toHaveText('0 / 2');
  const intersectionResponse = page.waitForResponse(response => response.url().includes('/intersection') && response.ok());
  await page.getByRole('button', { name: /^Intersekcje/ }).click();
  await expect(page.getByRole('button', { name: /^Intersekcje/ })).toHaveAttribute('aria-pressed', 'true');
  await intersectionResponse;
  await page.waitForTimeout(300);
  await page.screenshot({ path: testInfo.outputPath('analysis.png') });
  await page.locator('.relation-row').filter({ hasText: 'Intersekcja' }).first().click();
  await expect(page.locator('.scene-label')).toContainText('Izolacja części');
  await expect(page.locator('.scene-label')).toContainText('2 widocznych');
  await page.getByRole('button', { name: 'Wymaga poprawki', exact: true }).click();
  await expect(page.locator('.review-progress strong')).toHaveText('1 / 2');
  await expect(page.getByRole('button', { name: 'Wymaga poprawki', exact: true })).toHaveClass(/active/);
  await page.getByLabel('Notatka', { exact: true }).fill('Sprawdzić połączenie B-C');
  await page.getByLabel('Notatka', { exact: true }).blur();
  await expect(page.locator('.relation-row .review-status.fix')).toHaveCount(2);
  await expect(page.getByRole('button', { name: 'Wymaga poprawki', exact: true })).toHaveClass(/active/);
  await page.screenshot({ path: testInfo.outputPath('review.png') });
  await page.locator('.relation-row').filter({ hasText: 'Intersekcja' }).last().click();
  await expect(page.getByLabel('Notatka', { exact: true })).toHaveValue('Sprawdzić połączenie B-C');
  await page.getByRole('button', { name: 'Wróć do całego modelu' }).click();
  await page.getByTitle('Ukryj A.stl').click();
  await expect(page.locator('.scene-label')).toContainText('2 widocznych');
  await page.getByRole('button', { name: 'Analizuj połączenia' }).click();
  await expect(page.locator('.analysis-heading')).toContainText('Analiza zakończona');
  // Hidden A must still be included in the full analysis.
  await expect(page.locator('.statusbar')).toContainText('3 przeanalizowanych par');
  await expect(page.locator('.review-progress strong')).toHaveText('1 / 2');
  await page.getByRole('button', { name: /^Zaznaczone/ }).click();
  await page.getByRole('button', { name: 'Analizuj połączenia' }).click();
  await expect(page.getByRole('status')).toContainText('1 unikalnych par');
  await page.getByLabel('Pokaż także pary bez kontaktu').check();
  await expect(page.locator('.relation-row')).toHaveCount(6);
  expect(errors).toEqual([]);
});

function stlBox(name: string, x: number) {
  const v = [[0,0,0],[2,0,0],[2,2,0],[0,2,0],[0,0,2],[2,0,2],[2,2,2],[0,2,2]];
  const faces = [[0,2,1],[0,3,2],[4,5,6],[4,6,7],[0,1,5],[0,5,4],[1,2,6],[1,6,5],[2,3,7],[2,7,6],[3,0,4],[3,4,7]];
  return { name, mimeType: 'model/stl', buffer: Buffer.from(`solid box\n${faces.map(face => `facet normal 0 0 0\nouter loop\n${face.map(i => `vertex ${v[i][0] + x} ${v[i][1]} ${v[i][2]}`).join('\n')}\nendloop\nendfacet`).join('\n')}\nendsolid box`) };
}

test('import STL, gap witnesses, object selection and removal', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Importuj STL', exact: true })).toBeEnabled();
  await page.locator('input[type=file]').setInputFiles([stlBox('left.stl', 0), stlBox('right.stl', 2.05), stlBox('far.stl', 20)]);
  await expect(page.locator('.object-row')).toHaveCount(3);
  await expect(page.locator('.geometry-loading')).toHaveCount(0);
  await page.getByRole('button', { name: 'Analizuj połączenia' }).click();
  await expect(page.locator('.relation-row')).toHaveCount(2);
  await expect(page.locator('.check-part')).toHaveCount(3);
  await expect(page.locator('.relation-row').first()).toContainText('Szczelina');
  await expect(page.locator('.relation-row').first()).toContainText('0,05 mm');
  await page.getByRole('button', { name: /^Szczeliny/ }).click();
  await expect(page.getByRole('button', { name: /^Szczeliny/ })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('.view-legend')).toContainText('Najbliższe punkty');
  await page.locator('.object-row').filter({ hasText: 'left.stl' }).click();
  await page.locator('.object-row').filter({ hasText: 'right.stl' }).click({ modifiers: ['Shift'] });
  await expect(page.locator('.object-row.selected')).toHaveCount(2);
  await page.getByRole('button', { name: 'Izoluj zaznaczenie' }).click();
  await expect(page.locator('.scene-label')).toContainText('2 widocznych');
  await page.getByRole('button', { name: 'Pokaż wszystkie', exact: true }).click();
  await page.getByRole('button', { name: /^Zaznaczone/ }).click();
  await page.getByRole('button', { name: 'Analizuj połączenia' }).click();
  await expect(page.getByRole('status')).toContainText('1 unikalnych par');
  await page.locator('.object-row').filter({ hasText: 'far.stl' }).hover();
  await page.getByTitle('Usuń far.stl').click();
  await expect(page.locator('.object-row')).toHaveCount(2);
  await expect(page.locator('.check-part')).toHaveCount(2);
});
